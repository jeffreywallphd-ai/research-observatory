"""Portable explicit reprocessing boundary; selectors grant no authority."""

from typing import Protocol

from ..document_reprocessing import (
    ReprocessingAcceptance,
    ReprocessingAcceptedView,
    ReprocessingBatchView,
    ReprocessingCancel,
    ReprocessingContinue,
    ReprocessingCreate,
    ReprocessingPage,
    ReprocessingQueue,
    ReprocessingReconcile,
)


class DocumentReprocessingPort(Protocol):
    def create(self, command: ReprocessingCreate, *, input_factory, cancelled) -> ReprocessingBatchView: ...
    def read(self, batch_revision_id: str, *, cancelled) -> ReprocessingBatchView: ...
    def queue(self, *, after_batch_id: str | None, cancelled) -> ReprocessingQueue: ...
    def compare(self, batch_revision_id: str, item_id: str, *, offset: int, cancelled) -> ReprocessingPage: ...
    def reconcile(self, command: ReprocessingReconcile, *, cancelled) -> ReprocessingPage: ...
    def accept(self, command: ReprocessingAcceptance, *, cancelled) -> ReprocessingAcceptedView: ...
    def continue_item(self, command: ReprocessingContinue, *, input_factory, cancelled) -> ReprocessingBatchView: ...
    def cancel(self, command: ReprocessingCancel, *, cancelled) -> ReprocessingBatchView: ...
    def read_impact(self, batch_revision_id: str, item_id: str, *, cancelled) -> ReprocessingAcceptedView: ...
    def resume_impact(
        self, batch_revision_id: str, item_id: str, expected_checkpoint_sha256: str, *, cancelled
    ) -> ReprocessingAcceptedView: ...
