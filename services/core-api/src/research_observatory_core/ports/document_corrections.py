"""Portable correction port; typed selectors are not source or actor authority."""

from typing import Protocol

from ..document_correction_views import CorrectionAcceptedView, CorrectionImpactView, CorrectionPage, CorrectionQueue
from ..document_corrections import CorrectionAcceptance, CorrectionDiscard, CorrectionDraft, CorrectionSave
from ..document_revisions import AcceptedDocumentRevision


class DocumentCorrectionPort(Protocol):
    """Adapters hold current project/principal/source authority through delivery."""

    def save(self, command: CorrectionSave, *, cancelled) -> CorrectionDraft: ...
    def read(self, draft_revision_id: str, *, cancelled) -> CorrectionDraft: ...
    def discard(self, command: CorrectionDiscard, *, cancelled) -> CorrectionDraft: ...
    def accept(self, command: CorrectionAcceptance, *, cancelled) -> AcceptedDocumentRevision: ...
    def page(self, revision_id: str, *, draft_revision_id: str | None, offset: int, cancelled) -> CorrectionPage: ...
    def queue(self, *, after_job_id: str | None) -> CorrectionQueue: ...
    def impact(self, draft_revision_id: str, *, cancelled) -> CorrectionImpactView: ...
    def accepted_view(self, accepted) -> CorrectionAcceptedView: ...
