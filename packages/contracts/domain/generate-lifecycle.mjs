function validateProfile() {
  assert(schema.$schema === "https://json-schema.org/draft/2020-12/schema", "lifecycle schema must be Draft 2020-12");
  assert(Array.isArray(schema["x-research-observatory-semanticRules"]), "lifecycle schema must declare semantic rules");
  for (const definition of ["LifecycleProfile", "LifecycleSnapshot", "LifecycleCommand", "LifecycleTransition"]) {
    assert(schema.$defs?.[definition], "lifecycle schema must define " + definition);
  }
  assert(profile.schemaVersion === "1.0", "lifecycle profile schemaVersion must be 1.0");
  assert(profile.documentType === "research-observatory-domain-lifecycle-profile", "lifecycle profile type differs");
  assert(profile.profileVersion === "1.0.0", "lifecycle profile version differs");
  assert(Array.isArray(profile.subjects) && profile.subjects.length === expectedKinds.length, "lifecycle profile must cover eight subjects");
  assert(profile.subjects.map((subject) => subject.subjectKind).join("\n") === expectedKinds.join("\n"), "lifecycle subjects must be exact and ordered");
  for (const subject of profile.subjects) {
    assert(Array.isArray(subject.states) && subject.states.length >= 2, `${subject.subjectKind}: states missing`);
    assert(Array.isArray(subject.transitions) && subject.transitions.length >= 1, `${subject.subjectKind}: transitions missing`);
    const states = new Map();
    for (const state of subject.states) {
      assert(!states.has(state.id), `${subject.subjectKind}: duplicate state ${state.id}`);
      assert(typeof state.terminal === "boolean" && typeof state.description === "string", `${subject.subjectKind}: invalid state`);
      states.set(state.id, state);
    }
    assert(states.has(subject.initialState), `${subject.subjectKind}: initial state is unknown`);
    assert(states.get(subject.initialState).terminal === false, `${subject.subjectKind}: initial state cannot be terminal`);
    assert([...states.values()].some((state) => state.terminal), `${subject.subjectKind}: terminal state missing`);
    const selectors = new Set();
    for (const transition of subject.transitions) {
      assert(states.has(transition.from) && states.has(transition.to), `${subject.subjectKind}: transition state is unknown`);
      assert(transition.from !== transition.to, `${subject.subjectKind}: self transition is forbidden`);
      assert(transition.kind === "normal" || transition.kind === "reopen", `${subject.subjectKind}: transition kind invalid`);
      const selector = `${transition.from}\u0000${transition.command}`;
      assert(!selectors.has(selector), `${subject.subjectKind}: ambiguous transition ${transition.from}/${transition.command}`);
      selectors.add(selector);
      if (states.get(transition.from).terminal) {
        assert(transition.kind === "reopen", `${subject.subjectKind}: terminal state has a non-reopen transition`);
      }
    }
  }
}

